/** Deterministic, already-soft RGBA fields. No AI calls or source photographs. */
import sharp from 'sharp';
import { softField } from './lib/soft-fields.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const { size, layouts } = JSON.parse(readFileSync(join(root, 'design/soft-backgrounds.json'), 'utf8'));
const output = join(root, 'public/backgrounds/soft/v2');
mkdirSync(output, { recursive: true });

const concepts = [];
let total = 0;
for (const { fields, ...layout } of layouts) {
  const variants = {};
  for (const theme of ['dark', 'light']) {
    const filename = `${layout.id}-${theme}.webp`;
    const info = await sharp(softField({ size, theme, fields }), { raw: { width: size, height: size, channels: 4 } })
      .webp({ quality: 80, alphaQuality: 100, effort: 6 }).toFile(join(output, filename));
    variants[theme] = { src: `backgrounds/soft/v2/${filename}`, bytes: info.size };
    total += info.size;
  }
  concepts.push({ ...layout, variants });
}
writeFileSync(join(root, 'src/data/backgroundConcepts.ts'), `// Generated by scripts/soft-backgrounds.mjs from design/soft-backgrounds.json.\nexport type BackgroundTheme = 'dark' | 'light';\nexport const backgroundConcepts = ${JSON.stringify(concepts, null, 2)} as const;\nexport const backgroundFamilies = { edge: 'Боковой свет', depth: 'Глубина', diagonal: 'Диагональные поля', warmth: 'Тёплые полутона' } as const;\n`);
writeFileSync(join(output, 'manifest.json'), JSON.stringify({ version: 2, width: size, height: size, format: 'WebP RGBA, RGB q80, alpha q100', totalBytes: total, concepts }, null, 2) + '\n');
console.log(`${concepts.length} paired concepts, ${concepts.length * 2} RGBA ${size}×${size} files, ${total} bytes total (${(total / 1024).toFixed(1)} KiB).`);
