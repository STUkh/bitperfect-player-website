import sharp from 'sharp';
import { softField } from './lib/soft-fields.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const { size, layouts } = JSON.parse(readFileSync(join(root, 'design/flow-backgrounds.json'), 'utf8'));
const output = join(root, 'public/backgrounds/soft/v3');
mkdirSync(output, { recursive: true });
const concepts = [];
let totalBytes = 0;
for (const { fields, ...layout } of layouts) {
  const variants = {};
  for (const theme of ['dark', 'light']) {
    const filename = `${layout.id}-${theme}.webp`;
    const info = await sharp(softField({ size, theme, fields, edgeMode: 'vertical', quietCenter: 0.20, strengthScale: theme === 'light' ? 0.55 : 0.72 }), { raw: { width: size, height: size, channels: 4 } })
      .webp({ quality: 80, alphaQuality: 100, effort: 6 }).toFile(join(output, filename));
    variants[theme] = { src: `backgrounds/soft/v3/${filename}`, bytes: info.size };
    totalBytes += info.size;
  }
  concepts.push({ ...layout, variants });
}
writeFileSync(join(root, 'src/data/flowBackgrounds.ts'), `// Generated by scripts/flow-backgrounds.mjs.\nexport const flowBackgrounds = ${JSON.stringify(concepts, null, 2)} as const;\n`);
writeFileSync(join(output, 'manifest.json'), JSON.stringify({ version: 3, size, edgeMode: 'vertical', totalBytes, concepts }, null, 2) + '\n');
console.log(`4 full-bleed compositions, 8 WebP RGBA, ${totalBytes} bytes.`);
